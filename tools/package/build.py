def build_typescript(
    defs: list[entity_types.Definition],
    dcs_version: str,
    manifest_type: str,
    data: dict[str, str],
) -> None:
    sync_dir(TS_DIR / "data", data)
    src = {
        "types.ts": entity_types.typescript(defs),
        "json.d.ts": f"// {GENERATED}\n"
        'declare module "*.json" {\n'
        "  const value: unknown;\n"
        "  export default value;\n"
        "}\n",
    }
    pairs = series_types()
    type_names = sorted({t for _, t in pairs} | {manifest_type})
    lines = [
        f"// {GENERATED}",
        f"import type {{ {', '.join(type_names)} }} from './types.js';",
        "",
        "export * from './types.js';",
        "",
        "/** DCS version the data was extracted from. */",
        f"export const dcsVersion = {json.dumps(dcs_version)};",
        "",
        "/** A series: records keyed by id. */",
        "export type Series<T> = Readonly<Record<string, T>>;",
        "",
        "/** Record type of each series. */",
        "export interface SeriesTypes {",
        *(f"  {n}: {t};" for n, t in pairs),
        "}",
        "",
        "export type SeriesName = keyof SeriesTypes;",
        "",
        "export const seriesNames: readonly SeriesName[] = [",
        *(f"  {json.dumps(n)}," for n, _ in pairs),
        "];",
        "",
        "/** The record field each series is keyed by. */",
        "export const seriesKeys: Readonly<Record<SeriesName, string>> = {",
        *(f"  {json.dumps(n)}: {json.dumps(k)}," for n, k in series_keys().items()),
        "};",
        "",
        "/** Load a series bundle (`data/<name>.json`); the import is cached by the runtime. */",
        "export async function loadSeries<S extends SeriesName>(",
        "  name: S,",
        "): Promise<Series<SeriesTypes[S]>> {",
        "  const mod = (await import(`../data/${name}.json`, { with: { type: 'json' } })) as {",
        "    default: Series<SeriesTypes[S]>;",
        "  };",
        "  return mod.default;",
        "}",
        "",
        "/** Extraction provenance: DCS version, time, modules present. */",
        f"export async function loadManifest(): Promise<{manifest_type}> {{",
        "  const mod = await import('../data/manifest.json', { with: { type: 'json' } });",
        f"  return mod.default as {manifest_type};",
        "}",
    ]
    for n, t in pairs:
        lines += [
            "",
            f"/** `{n}` records ({t}) keyed by {SERIES[n].id_field}. */",
            f"export function load{entity_types.pascal(n)}(): Promise<Series<{t}>> {{",
            f"  return loadSeries({json.dumps(n)});",
            "}",
        ]
    lines += ["", "export * from './lookup.js';", "export * from './helpers.js';"]
    src["index.ts"] = "\n".join(lines) + "\n"
    for name in ("lookup.ts", "helpers.ts"):
        src[name] = (TS_DIR / name).read_text(encoding="utf-8")
    for n, t in pairs:
        src[f"{n}.ts"] = "\n".join(
            [
                f"// {GENERATED}",
                f"import data from '../data/{n}.json' with {{ type: 'json' }};",
                f"import type {{ {t} }} from './types.js';",
                "",
                f"/** `{n}` records keyed by {SERIES[n].id_field}. */",
                f"export const {camel(n)} = data as Readonly<Record<string, {t}>>;",
                f"export default {camel(n)};",
                "",
            ]
        )
    sync_dir(TS_DIR / "src", src)
    # Every bundle as an object literal typed as its series: `tsc --strict`
    # then checks each record against the generated types, excess keys included.
    sync_dir(
        TS_DIR / "test" / "generated",
        {
            f"{n}.ts": f"// {GENERATED}\n"
            f"import type {{ {t} }} from 'dcs-world-reference';\n\n"
            f"export const {camel(n)}: Record<string, {t}> = "
            f"{data[f'{n}.json'].rstrip()};\n"
            for n, t in pairs
        },
    )


