def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p.capitalize() for p in rest)


def sync_dir(directory: Path, files: dict[str, str]) -> None:
    """Make ``directory`` hold exactly ``files`` (name -> text); unchanged
    files are not rewritten."""
    sync_tree(directory, {directory / n: t.encode("utf-8") for n, t in files.items()})


def series_types() -> list[tuple[str, str]]:
    """(series, record type name) in registry order."""
    return [(s.name, entity_types.type_name(s.type_name)) for s in SERIES.values()]


def series_keys() -> dict[str, str]:
    """The field each series' bundle is keyed by."""
    return {n: s.id_field for n, s in SERIES.items()}


DCS_SUFFIX = re.compile(r" \(DCS [^)]*\)$")
DCS_KEYWORD = re.compile(r"^dcs-\d")


def package_json(text: str, version: str, dcs_version: str) -> str:
    """``package.json`` with ``version`` and ``dcsVersion`` (right after it) set."""
    pkg = json.loads(text)
    out: dict[str, Any] = {}
    for key, value in pkg.items():
        if key == "dcsVersion":
            continue
        out[key] = value
        if key == "version":
            out["version"] = version
            out["dcsVersion"] = dcs_version
    if "version" not in out:
        fail("no version in package.json")
    return json.dumps(out, indent=2) + "\n"


def package_lock(text: str, version: str, _dcs_version: str) -> str:
    """``package-lock.json`` with the root package's ``version`` set (top level
    and ``packages[""]``)."""
    lock = json.loads(text)
    root = lock.get("packages", {}).get("")
    if "version" not in lock or not isinstance(root, dict):
        fail("no version or root package in package-lock.json")
    lock["version"] = version
    root["version"] = version
    return json.dumps(lock, indent=2) + "\n"


def _toml_line(text: str, key: str, value: str) -> str:
    new, n = re.subn(
        rf"^{key} = .*$", lambda _: f"{key} = {value}", text, count=1, flags=re.M
    )
    if n != 1:
        fail(f"no {key} line in pyproject.toml")
    return new


def pyproject(text: str, version: str, dcs_version: str) -> str:
    """``pyproject.toml`` with ``version`` set, the DCS version at the end of
    ``description`` and as the ``dcs-<version>`` keyword."""
    meta = tomllib.loads(text)["project"]
    description = DCS_SUFFIX.sub("", meta["description"]) + f" (DCS {dcs_version})"
    keywords = [k for k in meta.get("keywords", []) if not DCS_KEYWORD.match(k)]
    keywords.append(f"dcs-{dcs_version}")
    text = _toml_line(text, "version", json.dumps(version))
    text = _toml_line(text, "description", json.dumps(description))
    return _toml_line(text, "keywords", json.dumps(keywords))


def sync_versions(version: str, dcs_version: str) -> None:
    """Set the package version (``VERSION``) and the DCS version (reference
    data manifest) in the npm and Python package metadata."""
    for path, update in (
        (TS_DIR / "package.json", package_json),
        (TS_DIR / "package-lock.json", package_lock),
        (PY_DIR / "pyproject.toml", pyproject),
    ):
        text = path.read_text(encoding="utf-8")
        new = update(text, version, dcs_version)
        if new != text:
            write_text_if_changed(path, new)
            print(f"Set {path.relative_to(REPO_ROOT)} to {version} (DCS {dcs_version})")


