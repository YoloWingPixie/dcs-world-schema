def build_python(
    defs: list[entity_types.Definition],
    dcs_version: str,
    manifest_type: str,
    data: dict[str, str],
) -> None:
    sync_dir(PY_PKG / "data", data)
    write_text_if_changed(PY_PKG / "entities.py", entity_types.python(defs))
    pairs = series_types()
    type_names = sorted({t for _, t in pairs} | {manifest_type})
    lines = [
        '"""DCS World reference data as typed dictionaries.',
        "",
        "Each loader returns one series, records keyed by id, read on first call",
        "and cached. Record types are in :mod:`dcs_world_reference.entities`.",
        "",
        GENERATED,
        '"""',
        "",
        "import json",
        "from collections.abc import Mapping",
        "from functools import cache",
        "from importlib.resources import files",
        "from typing import Any, Final, Literal, cast",
        "",
        "from .entities import (",
        *(f"    {t}," for t in type_names),
        ")",
        "",
        f"DCS_VERSION: Final = {json.dumps(dcs_version)}",
        '"""DCS version the data was extracted from."""',
        "",
        "SeriesName = Literal[",
        *(f"    {json.dumps(n)}," for n, _ in pairs),
        "]",
        "",
        "SERIES: Final[tuple[SeriesName, ...]] = (",
        *(f"    {json.dumps(n)}," for n, _ in pairs),
        ")",
        "",
        "SERIES_KEYS: Final[Mapping[SeriesName, str]] = {",
        *(f"    {json.dumps(n)}: {json.dumps(k)}," for n, k in series_keys().items()),
        "}",
        '"""The record field each series is keyed by."""',
        "",
        "",
        "@cache",
        "def _load(name: str) -> Any:",
        '    return json.loads(files(__name__).joinpath("data", f"{name}.json").read_text("utf-8"))',
        "",
        "",
        f"def manifest() -> {manifest_type}:",
        '    """Extraction provenance: DCS version, time, modules present."""',
        f'    return cast({manifest_type}, _load("manifest"))',
    ]
    for n, t in pairs:
        lines += [
            "",
            "",
            f"def {n}() -> Mapping[str, {t}]:",
            f'    """``{n}`` records keyed by {SERIES[n].id_field}."""',
            f"    return cast(Mapping[str, {t}], _load({json.dumps(n)}))",
        ]
    exported = [
        "DCS_VERSION",
        "SERIES",
        "SERIES_KEYS",
        "SeriesName",
        "manifest",
        *type_names,
        *(n for n, _ in pairs),
    ]
    lines += [
        "",
        "",
        "from .lookup import (  # noqa: E402",
        *(f"    {h}," for h in PY_LOOKUP),
        ")",
    ]
    lines += [
        "from .helpers import (  # noqa: E402",
        *(f"    {h}," for h in PY_HELPERS),
        ")",
    ]
    exported += PY_LOOKUP + PY_HELPERS
    lines += ["", "__all__ = [", *(f"    {json.dumps(e)}," for e in exported), "]"]
    write_text_if_changed(PY_PKG / "__init__.py", "\n".join(lines) + "\n")


