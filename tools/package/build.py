def lua_zip_name(version: str, dcs_version: str) -> str:
    return f"dcs-world-reference-lua-{version}-dcs{dcs_version}.zip"


def zip_lua(version: str, dcs_version: str) -> Path:
    """``dist/dcs-world-reference-lua-<version>-dcs<dcs version>.zip``, stable
    bytes for stable input."""
    out = DIST_DIR / lua_zip_name(version, dcs_version)
    files = [*sorted(LUA_PKG.glob("*.lua")), LUA_DIR / "README.md"]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for path in files:
            arc = path.relative_to(LUA_DIR).as_posix()
            info = zipfile.ZipInfo(arc, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            zf.writestr(info, path.read_bytes())
    write_bytes_if_changed(out, buf.getvalue())
    return out


